// Merge methodology/labels/sheet-NN.json (raw observations) through methodology/taxonomy.json
// (curated types, variants, aliases) into:
//   methodology/labels-canonical.json  every label with its canonical type/variant (+ raw name)
//   methodology/variants.json          canonical registry: definition, cues, examples, raw names merged in
//   methodology/label-summary.md       frequencies, "what to learn" lines, problems
// Raw label files are never rewritten. Change the taxonomy by editing taxonomy.json and re-running.
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, readJson, writeJsonAtomic } from './lib/progress.mjs';

const M = path.join(ROOT, 'methodology');
const sample = readJson(path.join(M, 'sample.json'), []);
const byS = new Map(sample.map((b) => [b.s, b]));
const taxonomy = readJson(path.join(M, 'taxonomy.json'), { types: {}, aliases: {} });
const files = fs.readdirSync(path.join(M, 'labels')).filter((f) => /^sheet-\d+\.json$/.test(f)).sort();

const labels = [];
const problems = [];
const rawDefs = new Map();
for (const f of files) {
  const sheet = readJson(path.join(M, 'labels', f), null);
  if (!sheet) { problems.push(`${f}: unreadable JSON`); continue; }
  for (const l of sheet.labels) {
    const b = byS.get(l.s);
    if (!b || b.id !== l.id) problems.push(`${f}: S${l.s} id ${l.id} does not match sample (${b?.id})`);
    if (!l.type || !l.variant) { problems.push(`${f}: S${l.s} missing type/variant`); continue; }
    const raw = `${l.type}/${l.variant}`;
    if (l.variantDefinition && !rawDefs.has(raw)) rawDefs.set(raw, l.variantDefinition);
    const [type, variant] = (taxonomy.aliases[raw]?.to ?? raw).split('/');
    if (!taxonomy.types[type]?.variants?.[variant]) problems.push(`${f}: S${l.s} ${raw} → ${type}/${variant} is not in taxonomy.json`);
    labels.push({ ...l, type, variant, raw, sheet: sheet.sheet });
  }
}
writeJsonAtomic(path.join(M, 'labels-canonical.json'), labels);

const variants = {};
for (const [type, t] of Object.entries(taxonomy.types)) {
  variants[type] = {};
  for (const [name, v] of Object.entries(t.variants)) {
    const members = labels.filter((l) => l.type === type && l.variant === name);
    variants[type][name] = { definition: v.definition, cues: v.cues ?? null, count: members.length,
      examples: members.map((l) => l.id), mergedFrom: [...new Set(members.map((l) => l.raw))].filter((r) => r !== `${type}/${name}`) };
  }
}
writeJsonAtomic(path.join(M, 'variants.json'), variants);

const counted = labels.filter((l) => l.type !== 'fragment');
const L = ['# Label summary', '', `_Generated by \`npm run labels\`: ${files.length} sheets, ${labels.length} labels (${labels.length - counted.length} fragments excluded from counts), ` +
  `${Object.keys(taxonomy.types).length} types, ${Object.values(taxonomy.types).reduce((n, t) => n + Object.keys(t.variants).length, 0)} canonical variants (from ${new Set(labels.map((l) => l.raw)).size} raw names)._`, ''];
L.push('## Types', '', '| type | blocks | variants used | definition |', '|---|---|---|---|');
const typeOrder = Object.keys(taxonomy.types).sort((a, b) => counted.filter((l) => l.type === b).length - counted.filter((l) => l.type === a).length);
for (const t of typeOrder) {
  const n = counted.filter((l) => l.type === t).length;
  L.push(`| ${t} | ${n} | ${Object.values(variants[t]).filter((v) => v.count).length}/${Object.keys(variants[t]).length} | ${taxonomy.types[t].definition} |`);
}
for (const t of typeOrder.filter((t) => t !== 'fragment')) {
  L.push('', `## ${t}`, '');
  for (const [name, v] of Object.entries(variants[t]).sort((a, b) => b[1].count - a[1].count))
    L.push(`- **${name}** (${v.count}): ${v.definition}${v.mergedFrom.length ? ` _[merged: ${v.mergedFrom.join(', ')}]_` : ''}${v.examples.length ? ` — e.g. ${v.examples.slice(0, 3).join(', ')}` : ''}`);
  const learn = counted.filter((l) => l.type === t && l.learn && l.learn !== '-').map((l) => `  - **${l.variant}**: ${l.learn} _(${l.id})_`);
  if (learn.length) L.push('', '<details><summary>What to learn</summary>', '', ...learn, '', '</details>');
}
const low = labels.filter((l) => l.confidence === 'low');
if (low.length) L.push('', '## Low-confidence labels', '', ...low.map((l) => `- S${l.s} ${l.id}: ${l.type}/${l.variant}`));
if (problems.length) L.push('', '## Problems', '', ...problems.map((p) => `- ${p}`));
fs.writeFileSync(path.join(M, 'label-summary.md'), L.join('\n') + '\n');
console.log(`${labels.length} labels from ${files.length} sheets → ${new Set(counted.map((l) => `${l.type}/${l.variant}`)).size} canonical variants in use; ${problems.length} problem(s) → methodology/label-summary.md`);
if (problems.length) for (const p of problems.slice(0, 15)) console.log(`  ! ${p}`);
