// Case-study numbers from the Phase 3 extraction (data/instances/*.json):
//   methodology/FINDINGS.md            coverage per section/type/variant, page arcs, rubric distributions
//   methodology/variants/<t>--<v>.jpg  contact sheet per variant (exemplars first), committed
//   npm run report
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { ROOT, readJson } from './lib/progress.mjs';

const M = path.join(ROOT, 'methodology');
const taxonomy = readJson(path.join(M, 'taxonomy.json'), null);
const canonical = (i) => (taxonomy.aliases[`${i.type}/${i.variant}`]?.to ?? `${i.type}/${i.variant}`).split('/');
const sectionOf = Object.fromEntries(Object.entries(taxonomy.sections).flatMap(([s, sec]) => sec.types.map((t) => [t, s])));

const docs = fs.readdirSync(path.join(ROOT, 'data', 'instances')).filter((f) => f !== 'index.json')
  .map((f) => readJson(path.join(ROOT, 'data', 'instances', f), null)).filter(Boolean);
const all = docs.flatMap((d) => d.instances.filter((i) => i.type !== 'fragment').map((i) => {
  const [type, variant] = canonical(i);
  return { ...i, type, variant, section: sectionOf[type], slug: d.slug };
}));
const N = docs.length;
const pct = (n) => `${Math.round((100 * n) / N)}%`;
const sitesWith = (pred) => new Set(all.filter(pred).map((i) => i.slug)).size;
const count = (arr, key) => arr.reduce((m, x) => { for (const k of [key(x)].flat()) if (k != null) m[k] = (m[k] ?? 0) + 1; return m; }, {});
const top = (m, n = 8) => Object.entries(m).sort((a, b) => b[1] - a[1]).slice(0, n);

const L = ['# Findings', '', `_Generated by \`npm run report\` from ${N} extracted sites and ${all.length} component instances._`, ''];

L.push('## How common is each section?', '', 'Share of sites with at least one instance of the section (any of its types).', '',
  '| section | sites | instances | most common types |', '|---|---|---|---|');
for (const [s, sec] of Object.entries(taxonomy.sections)) {
  const inst = all.filter((i) => i.section === s);
  L.push(`| ${sec.title} | ${pct(sitesWith((i) => i.section === s))} | ${inst.length} | ${top(count(inst, (i) => i.type), 3).map(([t, n]) => `${t} (${n})`).join(', ')} |`);
}

L.push('', '## Variants per type', '', 'Sites using each variant (an instance counts once per site).', '');
for (const [s, sec] of Object.entries(taxonomy.sections)) {
  L.push(`### ${sec.title}`, '');
  for (const t of sec.types) {
    const vs = Object.keys(taxonomy.types[t].variants).map((v) => [v, sitesWith((i) => i.type === t && i.variant === v)]).filter(([, n]) => n).sort((a, b) => b[1] - a[1]);
    if (!vs.length) continue;
    L.push(`- **${t}** (${sitesWith((i) => i.type === t)} sites): ${vs.map(([v, n]) => `${v} ${n}`).join(' · ')}`);
  }
  L.push('');
}

// Page arcs: what comes first and second, and where testers / glyphs / checkout sit in the page.
const seqs = docs.map((d) => (d.sequence ?? []).map((x) => sectionOf[canonical({ type: x.split('/')[0], variant: x.split('/')[1] })[0]]).filter(Boolean))
  .map((s) => s.filter((x, k) => x !== s[k - 1]));
L.push('## Page arcs', '', `Each site's sequence of sections (consecutive repeats merged). Median length: ${seqs.map((s) => s.length).sort((a, b) => a - b)[Math.floor(seqs.length / 2)]} sections.`, '');
L.push(`- **Opens with:** ${top(count(seqs, (s) => s[0]), 5).map(([k, n]) => `${taxonomy.sections[k]?.title} ${pct(n)}`).join(', ')}`);
L.push(`- **Second section:** ${top(count(seqs, (s) => s[1]), 5).map(([k, n]) => `${taxonomy.sections[k]?.title} ${pct(n)}`).join(', ')}`);
L.push(`- **Ends with:** ${top(count(seqs, (s) => s.at(-1)), 5).map(([k, n]) => `${taxonomy.sections[k]?.title} ${pct(n)}`).join(', ')}`);
const where = (sec) => {
  const pos = seqs.flatMap((s) => s.map((x, k) => (x === sec && s.length > 1 ? k / (s.length - 1) : null)).filter((x) => x != null));
  if (!pos.length) return '–';
  const q = (p) => Math.round(100 * pos.sort((a, b) => a - b)[Math.floor(p * (pos.length - 1))]);
  return `median ${q(0.5)}% down the page (middle half ${q(0.25)}–${q(0.75)}%)`;
};
for (const s of ['type-tester', 'glyph-table', 'design-details', 'checkout']) L.push(`- **${taxonomy.sections[s].title}** sits at ${where(s)}`);
L.push(`- **Most common arcs** (first four sections): ${top(count(seqs, (s) => s.slice(0, 4).map((x) => taxonomy.sections[x]?.title).join(' → ')), 6).map(([k, n]) => `${k} (${n})`).join('; ')}`, '');

// Rubric distributions across all instances.
L.push('## Look, feel and UX across all instances', '');
for (const k of ['colorMode', 'motion', 'interactivity', 'density', 'realism', 'mobile']) {
  const m = count(all, (i) => i.rubric?.[k]);
  const total = Object.values(m).reduce((a, b) => a + b, 0) || 1;
  L.push(`- **${k}:** ${top(m, 6).map(([v, n]) => `${v} ${Math.round((100 * n) / total)}%`).join(' · ')}`);
}
const heroCarrier = count(all.filter((i) => i.type === 'hero'), (i) => i.rubric?.carrier);
L.push(`- **Hero carriers:** ${top(heroCarrier).map(([v, n]) => `${v} ${n}`).join(' · ')}`);
const testerControls = count(all.filter((i) => i.type === 'type-tester'), (i) => i.rubric?.controls);
L.push(`- **Tester controls:** ${top(testerControls, 12).map(([v, n]) => `${v} ${n}`).join(' · ')}`);
const checkout = all.filter((i) => i.type === 'checkout');
L.push(`- **Checkout:** prices on the page in ${checkout.filter((i) => i.rubric?.pricesOnPage === true).length}/${checkout.length} instances; trials offered in ${checkout.filter((i) => i.rubric?.trial === true).length}; free fonts ${checkout.filter((i) => i.rubric?.free === true).length}`, '');

L.push('## Exemplars', '', 'Instances marked as strong references for rebuilding, by section.', '');
for (const [s, sec] of Object.entries(taxonomy.sections)) {
  const ex = all.filter((i) => i.section === s && i.exemplar);
  if (ex.length) L.push(`- **${sec.title}** (${ex.length}): ${ex.slice(0, 14).map((i) => `${i.slug}#${i.blocks[0]} (${i.variant})`).join(', ')}${ex.length > 14 ? ', …' : ''}`);
}
fs.writeFileSync(path.join(M, 'FINDINGS.md'), L.join('\n') + '\n');

// Contact sheets per variant: up to 12 instances, exemplars first, then by confidence.
const out = path.join(M, 'variants');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
const rank = { high: 0, medium: 1, low: 2 };
const TW = 330, TH = 250, LH = 22;
const byVariant = all.reduce((m, i) => m.set(`${i.type}--${i.variant}`, [...(m.get(`${i.type}--${i.variant}`) ?? []), i]), new Map());
for (const [key, list] of byVariant) {
  const items = list.map((i) => ({ i, crop: path.join(ROOT, 'archive', i.slug, 'blocks', `${i.blocks[0]}.jpg`) })).filter((x) => fs.existsSync(x.crop))
    .sort((a, b) => Number(!!b.i.exemplar) - Number(!!a.i.exemplar) || (rank[a.i.confidence] ?? 3) - (rank[b.i.confidence] ?? 3)).slice(0, 12);
  if (!items.length) continue;
  const comps = [];
  for (const [k, { i, crop }] of items.entries()) {
    const left = (k % 4) * TW, topY = Math.floor(k / 4) * (TH + LH);
    const label = `${i.exemplar ? '★ ' : ''}${i.slug}#${i.blocks[0]}`.replace(/&/g, '&amp;').slice(0, 46);
    comps.push({ input: Buffer.from(`<svg width="${TW}" height="${LH}"><rect width="100%" height="100%" fill="#111"/><text x="4" y="15" font-family="DejaVu Sans" font-size="11" fill="${i.exemplar ? '#ffd400' : '#fff'}">${label}</text></svg>`), left, top: topY });
    const { data, info } = await sharp(crop).resize({ width: TW - 6 }).toBuffer({ resolveWithObject: true });
    comps.push({ input: info.height > TH - 4 ? await sharp(data).extract({ left: 0, top: 0, width: info.width, height: TH - 4 }).toBuffer() : data, left: left + 3, top: topY + LH });
  }
  await sharp({ create: { width: Math.min(4, items.length) * TW, height: Math.ceil(items.length / 4) * (TH + LH), channels: 3, background: '#666' } })
    .composite(comps).jpeg({ quality: 72 }).toFile(path.join(out, `${key}.jpg`));
}
console.log(`${N} sites, ${all.length} instances → methodology/FINDINGS.md; ${byVariant.size} variant sheets → methodology/variants/`);
