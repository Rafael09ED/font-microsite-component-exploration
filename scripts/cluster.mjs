// Phase 2.3: check the labelled sample by component similarity.
//   1. Per-variant contact sheets (methodology/variants/<type>--<variant>.jpg, committed) to eyeball each group.
//   2. Which block features distinguish each type and variant (mean z-score vs. the rest of the type).
//   3. Leave-one-out nearest-centroid accuracy: can DOM features alone predict type and variant?
//      High accuracy means Phase 3 can pre-suggest labels; low accuracy means it needs eyes.
//
//   npm run cluster      → methodology/cluster-report.md
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { ROOT, readJson } from './lib/progress.mjs';

const M = path.join(ROOT, 'methodology');
const sample = new Map(readJson(path.join(M, 'sample.json'), []).map((b) => [b.id, b]));
const blocks = new Map();
for (const f of fs.readdirSync(path.join(ROOT, 'data', 'blocks')))
  for (const b of readJson(path.join(ROOT, 'data', 'blocks', f), { blocks: [] }).blocks) blocks.set(b.id, b);

// Canonical labels (after taxonomy aliases) — run `npm run labels` first.
const labels = readJson(path.join(M, 'labels-canonical.json'), [])
  .filter((l) => blocks.has(l.id) && !['fragment', 'chrome'].includes(l.type))
  .map((l) => ({ ...l, block: blocks.get(l.id) }));

// Feature vector: numeric block features plus text hints as 0/1.
const dims = Object.keys(labels[0].block.vector);
const hintDims = Object.keys(labels[0].block.hints);
const raw = (b) => [...dims.map((d) => b.vector[d]), ...hintDims.map((h) => (b.hints[h] ? 1 : 0))];
const names = [...dims, ...hintDims.map((h) => `hint:${h}`)];
const X = labels.map((l) => raw(l.block));
const mean = names.map((_, i) => X.reduce((s, x) => s + x[i], 0) / X.length);
const sd = names.map((_, i) => Math.sqrt(X.reduce((s, x) => s + (x[i] - mean[i]) ** 2, 0) / X.length) || 1);
labels.forEach((l, k) => { l.z = X[k].map((v, i) => (v - mean[i]) / sd[i]); });

const centroid = (rows) => names.map((_, i) => rows.reduce((s, r) => s + r.z[i], 0) / rows.length);
const dist = (a, b) => Math.sqrt(a.reduce((s, v, i) => s + (v - b[i]) ** 2, 0));
const groupBy = (rows, key) => rows.reduce((m, r) => m.set(key(r), [...(m.get(key(r)) ?? []), r]), new Map());

// Leave-one-out nearest centroid over groups with ≥ 2 members.
function looAccuracy(rows, key) {
  const groups = groupBy(rows, key);
  const eligible = rows.filter((r) => groups.get(key(r)).length >= 2);
  let hit = 0;
  for (const r of eligible) {
    let best = null, bestD = Infinity;
    for (const [g, members] of groups) {
      const others = members.filter((m) => m !== r);
      if (!others.length) continue;
      const d = dist(r.z, centroid(others));
      if (d < bestD) { bestD = d; best = g; }
    }
    if (best === key(r)) hit++;
  }
  return { n: eligible.length, acc: eligible.length ? hit / eligible.length : null };
}

// Top distinguishing features of a group vs. a reference set.
function signature(members, reference) {
  const c = centroid(members), r = centroid(reference);
  return names.map((n, i) => ({ n, d: c[i] - r[i] })).sort((a, b) => Math.abs(b.d) - Math.abs(a.d)).slice(0, 4)
    .map(({ n, d }) => `${d > 0 ? '↑' : '↓'}${n}`).join(' ');
}

const L = ['# Cluster report (Phase 2.3)', '', `_Generated by \`npm run cluster\` from ${labels.length} labelled blocks (excluding fragment/chrome)._`, ''];
const typeAcc = looAccuracy(labels, (l) => l.type);
L.push(`**Type from DOM features (leave-one-out nearest centroid):** ${(typeAcc.acc * 100).toFixed(0)}% of ${typeAcc.n}`, '');
L.push('| type | n | variants | variant accuracy | what distinguishes the type |', '|---|---|---|---|---|');
const byType = groupBy(labels, (l) => l.type);
for (const [type, rows] of [...byType].sort((a, b) => b[1].length - a[1].length)) {
  const va = looAccuracy(rows, (l) => l.variant);
  L.push(`| ${type} | ${rows.length} | ${new Set(rows.map((r) => r.variant)).size} | ${va.acc == null ? '–' : `${(va.acc * 100).toFixed(0)}% of ${va.n}`} | ${signature(rows, labels)} |`);
}
for (const [type, rows] of [...byType].sort((a, b) => b[1].length - a[1].length)) {
  L.push('', `## ${type}`, '');
  for (const [variant, members] of [...groupBy(rows, (l) => l.variant)].sort((a, b) => b[1].length - a[1].length))
    L.push(`- **${variant}** (${members.length})${members.length >= 2 && rows.length > members.length ? ` — ${signature(members, rows)}` : ''} — ${members.slice(0, 4).map((m) => m.id).join(', ')}`);
}
fs.writeFileSync(path.join(M, 'cluster-report.md'), L.join('\n') + '\n');

// Per-variant contact sheets: up to 12 tiles, 4 across. Committed (unlike archive/), so the
// pattern pages show images without the local archive.
const out = path.join(M, 'variants');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
const TW = 330, TH = 280, LH = 22;
for (const [key, members] of groupBy(labels, (l) => `${l.type}--${l.variant}`)) {
  const items = members.filter((m) => sample.get(m.id)?.crop).slice(0, 12);
  if (!items.length) continue;
  const cols = Math.min(4, items.length), rows = Math.ceil(items.length / 4);
  const comps = [];
  for (const [i, m] of items.entries()) {
    const left = (i % 4) * TW, top = Math.floor(i / 4) * (TH + LH);
    comps.push({ input: Buffer.from(`<svg width="${TW}" height="${LH}"><rect width="100%" height="100%" fill="#111"/><text x="4" y="15" font-family="DejaVu Sans" font-size="11" fill="#fff">${m.id.replace(/&/g, '&amp;').slice(0, 48)}</text></svg>`), left, top });
    comps.push({ input: await sharp(path.join(ROOT, sample.get(m.id).crop)).resize({ width: TW - 6, height: TH - 4, fit: 'cover', position: 'top' }).toBuffer(), left: left + 3, top: top + LH });
  }
  await sharp({ create: { width: cols * TW, height: rows * (TH + LH), channels: 3, background: '#666' } }).composite(comps).jpeg({ quality: 75 }).toFile(path.join(out, `${key}.jpg`));
}
console.log(`type accuracy ${(typeAcc.acc * 100).toFixed(0)}% (n=${typeAcc.n}); ${byType.size} types → methodology/cluster-report.md, methodology/variants/`);
