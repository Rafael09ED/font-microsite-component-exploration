// Generate methodology/patterns/<type>.md from taxonomy.json, rubric.json and the Phase 3 instances
// (falling back to the Phase 2 sample labels before extraction): one page per component type with its
// variants, recognition cues, frequency across sites, examples (exemplars first), observed
// look/feel/ux and "what to learn". Re-run after any taxonomy, label or extraction change.
//   npm run patterns
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, readJson } from './lib/progress.mjs';

const M = path.join(ROOT, 'methodology');
const taxonomy = readJson(path.join(M, 'taxonomy.json'), null);
const rubric = readJson(path.join(M, 'rubric.json'), { perType: {} });
const INST = path.join(ROOT, 'data', 'instances');
const canonical = (i) => (taxonomy.aliases[`${i.type}/${i.variant}`]?.to ?? `${i.type}/${i.variant}`).split('/');
const phase3 = fs.existsSync(INST) ? fs.readdirSync(INST).filter((f) => f !== 'index.json').map((f) => readJson(path.join(INST, f), null)).filter(Boolean) : [];
const rank = { high: 0, medium: 1, low: 2 };
// One row per instance: Phase 3 when available, else the Phase 2 sample labels.
const labels = (phase3.length
  ? phase3.flatMap((d) => d.instances.map((i) => { const [type, variant] = canonical(i); return { ...i, type, variant, id: `${d.slug}#${i.blocks[0]}`, crop: `archive/${d.slug}/blocks/${i.blocks[0]}.jpg` }; }))
  : readJson(path.join(M, 'labels-canonical.json'), []).map((l) => ({ ...l, crop: `archive/${l.id.replace('#', '/blocks/')}.jpg` })))
  .filter((l) => l.type !== 'fragment')
  .sort((a, b) => Number(!!b.exemplar) - Number(!!a.exemplar) || (rank[a.confidence] ?? 3) - (rank[b.confidence] ?? 3));
const sites = (rows) => new Set(rows.map((l) => l.id.split('#')[0])).size;
const source = phase3.length ? `the Phase 3 extraction of ${phase3.length} sites` : 'the 250-block Phase 2 sample';
const out = path.join(M, 'patterns');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

const index = ['# Patterns', '', '_Generated by `npm run patterns`. The 8 sections are the original component list; each holds the component types found in the study (the core type first, then discovered ones), and each type has one page. ' +
  `Counts are sites using the type or variant, from ${source}. Rows list exemplars (★) first. ` +
  'Contact sheets live in `methodology/variants/` (committed); the per-example links open full crops from the local `archive/` (not in git, run `npm run archive && npm run blocks`)._'];
const sectionOf = Object.fromEntries(Object.entries(taxonomy.sections).flatMap(([s, sec]) => sec.types.map((t) => [t, s])));
for (const [, sec] of Object.entries(taxonomy.sections)) {
  index.push('', `## ${sec.title}`, '', sec.definition, '', '| type | sites | variants | |', '|---|---|---|---|');
  for (const type of sec.types) {
    const t = taxonomy.types[type];
    index.push(`| [${type}](patterns/${type}.md) | ${sites(labels.filter((l) => l.type === type))} | ${Object.keys(t.variants).length} | ${t.definition} |`);
  }
}
const types = Object.entries(taxonomy.types).filter(([t]) => t !== 'fragment');

for (const [type, t] of types) {
  const tl = labels.filter((l) => l.type === type);
  const sec = taxonomy.sections[sectionOf[type]];
  const L = [`# ${type}`, '', `_Section: ${sec.title}${sec.types[0] === type ? '' : ` (discovered type, alongside ${sec.types[0]})`}_`, '', t.definition, '', `${tl.length} instances on ${sites(tl)} sites (${source}).`, ''];
  L.push('| variant | sites | definition | recognise by |', '|---|---|---|---|');
  const vs = Object.entries(t.variants).sort((a, b) => sites(tl.filter((l) => l.variant === b[0])) - sites(tl.filter((l) => l.variant === a[0])));
  for (const [name, v] of vs) L.push(`| [${name}](#${name}) | ${sites(tl.filter((l) => l.variant === name))} | ${v.definition} | ${v.cues ?? ''} |`);
  if (rubric.perType[type]) {
    L.push('', '## Rubric', '', 'Recorded for every instance in Phase 3, in addition to the cross-cutting attributes in `rubric.json`:', '');
    for (const [k, a] of Object.entries(rubric.perType[type])) L.push(`- **${k}**: ${(a.multi ? `any of ${a.multi.join(', ')}` : a.values.join(' | '))}${a.how ? ` (${a.how})` : ''}`);
  }
  for (const [name, v] of vs) {
    const members = tl.filter((l) => l.variant === name);
    L.push('', `## ${name}`, '', `${v.definition}`, '', `**Recognise by:** ${v.cues ?? '-'}`);
    if (!members.length) { L.push('', '_No instance yet._'); continue; }
    if (fs.existsSync(path.join(M, 'variants', `${type}--${name}.jpg`))) L.push('', `![${type}/${name} examples](../variants/${type}--${name}.jpg)`);
    L.push('', '| example | look | feel | ux | learn |', '|---|---|---|---|---|');
    for (const m of members.slice(0, 15)) {
      const link = fs.existsSync(path.join(ROOT, m.crop)) ? `[${m.exemplar ? '★ ' : ''}${m.id}](../../${m.crop})` : `${m.exemplar ? '★ ' : ''}${m.id}`;
      L.push(`| ${link} | ${m.look ?? ''} | ${m.feel ?? ''} | ${m.ux ?? ''} | ${m.learn ?? ''} |`.replace(/\n/g, ' ').replace(/\|(?=[^|]*\|[^|]*$)/g, '|'));
    }
    if (members.length > 15) L.push('', `_…and ${members.length - 15} more in the gallery (\`npm run app\`)._`);
  }
  fs.writeFileSync(path.join(out, `${type}.md`), L.join('\n') + '\n');
}
fs.writeFileSync(path.join(M, 'PATTERNS.md'), index.join('\n') + '\n');
console.log(`${types.length} pattern pages → methodology/patterns/, index → methodology/PATTERNS.md`);
