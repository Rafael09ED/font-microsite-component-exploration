// Generate methodology/patterns/<type>.md from taxonomy.json, rubric.json and the canonical labels:
// one page per component type with its variants, recognition cues, sample frequency, examples,
// observed look/feel/ux and "what to learn". Re-run after any taxonomy or label change.
//   npm run patterns
import fs from 'node:fs';
import path from 'node:path';
import { ROOT, readJson } from './lib/progress.mjs';

const M = path.join(ROOT, 'methodology');
const taxonomy = readJson(path.join(M, 'taxonomy.json'), null);
const rubric = readJson(path.join(M, 'rubric.json'), { perType: {} });
const labels = readJson(path.join(M, 'labels-canonical.json'), []).filter((l) => l.type !== 'fragment');
const sample = new Map(readJson(path.join(M, 'sample.json'), []).map((b) => [b.id, b]));
const out = path.join(M, 'patterns');
fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });

const index = ['# Patterns', '', '_Generated by `npm run patterns`. One page per component type. Counts come from the 250-block sample, so they show relative frequency in the sample, not across all 181 sites. Contact sheets live in `methodology/variants/` (committed); the per-example links open full crops from the local `archive/` (not in git, run `npm run archive && npm run blocks`)._', '',
  '| type | sample blocks | variants | |', '|---|---|---|---|'];
const types = Object.entries(taxonomy.types).filter(([t]) => t !== 'fragment')
  .sort((a, b) => labels.filter((l) => l.type === b[0]).length - labels.filter((l) => l.type === a[0]).length);

for (const [type, t] of types) {
  const tl = labels.filter((l) => l.type === type);
  index.push(`| [${type}](patterns/${type}.md) | ${tl.length} | ${Object.keys(t.variants).length} | ${t.definition} |`);
  const L = [`# ${type}`, '', t.definition, '', `Sample: ${tl.length} blocks from ${new Set(tl.map((l) => l.id.split('#')[0])).size} sites.`, ''];
  L.push('| variant | n | definition | recognise by |', '|---|---|---|---|');
  const vs = Object.entries(t.variants).sort((a, b) => tl.filter((l) => l.variant === b[0]).length - tl.filter((l) => l.variant === a[0]).length);
  for (const [name, v] of vs) L.push(`| [${name}](#${name}) | ${tl.filter((l) => l.variant === name).length} | ${v.definition} | ${v.cues ?? ''} |`);
  if (rubric.perType[type]) {
    L.push('', '## Rubric', '', 'Recorded for every instance in Phase 3, in addition to the cross-cutting attributes in `rubric.json`:', '');
    for (const [k, a] of Object.entries(rubric.perType[type])) L.push(`- **${k}**: ${(a.multi ? `any of ${a.multi.join(', ')}` : a.values.join(' | '))}${a.how ? ` (${a.how})` : ''}`);
  }
  for (const [name, v] of vs) {
    const members = tl.filter((l) => l.variant === name);
    L.push('', `## ${name}`, '', `${v.definition}`, '', `**Recognise by:** ${v.cues ?? '-'}`);
    if (!members.length) { L.push('', '_No instance in the sample yet._'); continue; }
    if (fs.existsSync(path.join(M, 'variants', `${type}--${name}.jpg`))) L.push('', `![${type}/${name} examples](../variants/${type}--${name}.jpg)`);
    L.push('', '| example | look | feel | ux | learn |', '|---|---|---|---|---|');
    for (const m of members) {
      const s = sample.get(m.id);
      const link = s?.crop ? `[${m.id}](../../${s.crop})` : m.id;
      L.push(`| ${link} | ${m.look ?? ''} | ${m.feel ?? ''} | ${m.ux ?? ''} | ${m.learn ?? ''} |`.replace(/\n/g, ' '));
    }
  }
  fs.writeFileSync(path.join(out, `${type}.md`), L.join('\n') + '\n');
}
fs.writeFileSync(path.join(M, 'PATTERNS.md'), index.join('\n') + '\n');
console.log(`${types.length} pattern pages → methodology/patterns/, index → methodology/PATTERNS.md`);
